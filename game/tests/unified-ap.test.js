import test from 'node:test';
import assert from 'node:assert/strict';
import { createNewGame, normalizeGame } from '../js/game-state.js';
import { availableAp, gainAp, normalizeAp } from '../js/ap.js';
import { changeJob, learnSkill, learnCommon, commonBlock, upgradeSkill, isLearned } from '../js/growth.js';
import { gainXp, xpToNext } from '../js/character.js';
import { applyTrainingAnswer } from '../js/training.js';
import { GameSession } from '../js/save.js';
import { realGameData, MemoryStorage } from './helpers.js';
const data = realGameData();
const fresh = () => createNewGame(data, ['warrior', 'knight', 'black_mage', 'white_mage', 'thief', 'bard'].map((job) => ({ job, name: job, icon: 'x' })));

test('転職後の技能修得・強化と共通パッシブで同じAPを使い、仲間とは共有しない', () => {
  const game = fresh();
  const member = game.party[0];
  member.ap = 1000;
  member.lv = 5;
  const fire = data.skills.get('black_mage_A01');
  const node = data.commonTree.find((entry) => entry.id === 'vit1');
  assert.throws(() => learnSkill(data, member, fire.id), /転職/);
  changeJob(data, game, 0, 'black_mage');
  assert.equal(member.ap, 1000);
  learnSkill(data, member, fire.id);
  upgradeSkill(data, member, fire.id);
  learnCommon(data, member, node.id);
  const expected = 1000 - fire.apToLearn - fire.effect.levels[0].ap - node.apToLearn;
  assert.equal(member.ap, expected);
  assert.equal(game.party[1].ap, data.basicJobRules.starting_ap);
  changeJob(data, game, 0, 'warrior');
  assert.equal(member.ap, expected);
  assert.ok(isLearned(member, fire));
  assert.ok(member.common.includes(node.id));
});

test('AP不足・レベル不足・二重修得は残高を変えず、レベルだけでAPを付与しない', () => {
  const member = fresh().party[0];
  const node = data.commonTree.find((entry) => entry.id === 'vit1');
  member.ap = node.apToLearn - 1;
  member.lv = node.level;
  assert.match(commonBlock(data, member, node), /AP/);
  assert.throws(() => learnCommon(data, member, node.id), /AP/);
  assert.equal(member.ap, node.apToLearn - 1);
  member.ap = node.apToLearn;
  member.lv = 1;
  assert.throws(() => learnCommon(data, member, node.id), /Lv/);
  gainXp(data, member, xpToNext(data, 1));
  assert.equal(member.ap, node.apToLearn);
  learnCommon(data, member, node.id);
  assert.equal(member.ap, 0);
  assert.throws(() => learnCommon(data, member, node.id), /覚えている/);
  assert.equal(member.ap, 0);
});

test('旧ジョブ別AP・共通ポイント・訓練小数・旧技能費用を一度だけ合算する', () => {
  const game = fresh();
  const member = game.party[0];
  delete member.apVersion;
  delete member.visitedJobs;
  delete member.skillAcquisitionVersion;
  delete member.jobMasterVersion;
  member.lv = 5;
  member.ap = { warrior: 17, black_mage: 0, thief: 23 };
  member.common = ['vit1'];
  const old = data.skillMigration.retired_skills.find((skill) => skill.id === 'warrior_p1_s2');
  member.learned = [old.id];
  member.trainingCredit = { xp: 0.9, ap: { warrior: 0.8, thief: 0.7 } };
  const run = { snapshot: structuredClone(game) };
  normalizeGame(data, game, run);
  const expected = 71 + old.ap;
  assert.equal(member.ap, expected);
  assert.equal(member.trainingCredit.ap, 0.5);
  assert.equal(member.trainingCredit.xp, 0.9);
  assert.deepEqual(member.common, ['vit1']);
  assert.deepEqual(member.learned, []);
  assert.ok(member.visitedJobs.includes('black_mage'));
  assert.ok(!isLearned(member, data.skills.get('black_mage_A01')));
  assert.equal(run.snapshot.party[0].ap, expected);
  const before = structuredClone({ game, run });
  normalizeGame(data, game, run);
  assert.deepEqual({ game, run }, before);
  member.lv = 6;
  normalizeAp(data, member);
  assert.equal(member.ap, expected);
});

test('初期AP・戦闘AP相当・訓練APを同じ残高へ加え、保存再開で維持する', () => {
  const game = fresh();
  const member = game.party[0];
  const start = member.ap;
  gainAp(data, member, 7);
  for (let n = 0; n < 25; n += 1) applyTrainingAnswer(data, game, { kind: 'word', id: String(n), day: 1, passed: true });
  assert.equal(member.ap, start + 8);
  const storage = new MemoryStorage();
  const session = new GameSession({ storage });
  session.startNew(game);
  const loaded = new GameSession({ storage });
  normalizeGame(data, loaded.game);
  assert.equal(availableAp(data, loaded.game.party[0]), start + 8);
  assert.deepEqual(loaded.game.party[0].visitedJobs, ['warrior']);
});
